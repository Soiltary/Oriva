import {call,sql,b} from './accounts.mjs';
import assert from 'node:assert/strict';
const cookie=b.cookie;
const base=await call('library','GET',undefined,cookie),version=base.data.version;
const article=await call('items','POST',{kind:'article',title:'Large article',body:'س'.repeat(10000)},cookie);
assert.equal(article.status,201);
let delta=await call('library?afterVersion='+version,'GET',undefined,cookie);
assert.equal(delta.data.items.length,1);assert.equal(delta.data.items[0].body_preview,1);assert.equal(delta.data.items[0].body.length,500);
assert.equal((await call('items/'+article.data.item.id,'GET',undefined,cookie)).data.item.body.length,10000);
const beforeDelete=delta.data.version;
await call('items/'+article.data.item.id,'DELETE',{revision:1},cookie);
delta=await call('library?afterVersion='+beforeDelete,'GET',undefined,cookie);assert.equal(delta.data.items.length,1);assert.ok(delta.data.items[0].deleted_at);
const group=await call('collections','POST',{name:'Before rename'},cookie);
const link=await call('items','POST',{url:'https://delta.test',collection:'Before rename'},cookie);
const beforeRename=(await call('library','GET',undefined,cookie)).data.version;
assert.equal((await call('collections/'+group.data.collection.id,'PATCH',{revision:1,name:'After rename'},cookie)).status,200);
delta=await call('library?afterVersion='+beforeRename,'GET',undefined,cookie);assert.equal(delta.data.items.length,1);assert.equal(delta.data.items[0].collection,'After rename');
assert.equal(sql.prepare('SELECT COUNT(*) n FROM item_revisions WHERE item_id=?').get(link.data.item.id).n,1);
console.log('PASS incremental create, complete-document fetch, explicit previews, trash tombstones and collection-rename changes.');
